SEED_TERMS = RETAILER_TERMS + CATEGORY_TERMS + BRAND_TERMS


def _escape_like(term: str) -> str:
    return term.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_")


def _connect() -> sqlite3.Connection:
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS keywords (
            term TEXT PRIMARY KEY,
            freq INTEGER NOT NULL DEFAULT 1
        )
        """
    )
    return conn


def seed() -> None:
    """카테고리/리테일러/브랜드 키워드로 인덱스를 채운다.

    이미 있는 단어는 건드리지 않고(빈도 유지) 빠진 시드 단어만 추가하므로,
    실사용으로 쌓인 데이터가 있는 상태에서 앱을 재시작해도 안전하게 반복 호출할 수 있다.
    """
    conn = _connect()
    try:
        conn.executemany(
            "INSERT OR IGNORE INTO keywords (term, freq) VALUES (?, 1)",
            [(term,) for term in SEED_TERMS],
        )
        conn.commit()
    finally:
        conn.close()


def record_terms(terms: list[str]) -> None:
    """실제 검색어/판정된 상품명을 인덱스에 반영해 빈도를 높인다.

    빈 문자열이나 지나치게 긴 문장(설명문 등)은 자동완성 후보로 부적절하므로 걸러낸다.
    """
    cleaned = {
        t.strip()
        for t in terms
        if t and t.strip() and len(t.strip()) <= MAX_TERM_LENGTH
    }
    if not cleaned:
        return
    conn = _connect()
    try:
        conn.executemany(
            """
            INSERT INTO keywords (term, freq) VALUES (?, 1)
            ON CONFLICT(term) DO UPDATE SET freq = freq + 1
            """,
            [(term,) for term in cleaned],
        )
        conn.commit()
    finally:
        conn.close()


def suggest(prefix: str, limit: int = 8) -> list[str]:
    """prefix로 시작하는 키워드를 빈도순으로 반환한다."""
    prefix = prefix.strip()
    if not prefix:
        return []
    conn = _connect()
    try:
        rows = conn.execute(
            """
            SELECT term FROM keywords
            WHERE term LIKE ? || '%' ESCAPE '\\'
            ORDER BY freq DESC, LENGTH(term) ASC, term ASC
            LIMIT ?
            """,
            (_escape_like(prefix), limit),
        ).fetchall()
        return [row[0] for row in rows]
    finally:
        conn.close()


async def suggest_merged(prefix: str, limit: int = 8) -> list[str]:
    """로컬 인덱스(suggest, 우리 서비스 실사용 기반) 기반 자동완성."""
    prefix = prefix.strip()
    if not prefix:
        return []
    return await asyncio.to_thread(suggest, prefix, limit)
