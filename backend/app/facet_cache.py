_STATIC_FACET_PATTERN = re.compile(
    "^(" + "|".join(re.escape(k) for k in STATIC_FACETS) + r")\s*$"
)


def lookup(query: str) -> list[ClarifyFacet] | None:
    """정적 캐시에 있는 카테고리면 그 facet을 즉시 반환한다(검색/LLM 호출
    없음) - 없으면 None이며, 호출부는 이때 기존처럼 실제 검색+추출 경로를
    타야 한다."""
    match = _STATIC_FACET_PATTERN.match(query.strip())
    if match is None:
        return None
    return [ClarifyFacet(**f) for f in STATIC_FACETS[match.group(1)]]
